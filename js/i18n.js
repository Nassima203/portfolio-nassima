const LANGS = ['fr', 'en'];
const TRANSLATED_ATTRS = ['alt', 'placeholder', 'aria-label'];

let currentLang = 'fr';

// Traduit une chaîne utilisée par le JS (messages du formulaire, menu burger...)
const t = (fr) => (currentLang === 'en' && EN[fr]) || fr;

// On mémorise une fois le texte français de chaque nœud traduisible, pour pouvoir revenir en FR
const textTargets = [];
const attrTargets = [];

const collectTargets = () => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => (node.parentElement.closest('script, style') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT)
  });

  while (walker.nextNode()) {
    const node = walker.currentNode;
    const key = node.data.trim();
    if (key && EN[key]) textTargets.push({ node, fr: node.data, key });
  }

  document.querySelectorAll(TRANSLATED_ATTRS.map(a => `[${a}]`).join(',')).forEach(el => {
    TRANSLATED_ATTRS.forEach(attr => {
      const fr = el.getAttribute(attr);
      if (fr && EN[fr.trim()]) attrTargets.push({ el, attr, fr });
    });
  });
};

const applyLang = (lang) => {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = t('Nassima Adli — Développeuse Web Fullstack');

  // Les espaces autour du texte sont conservés (ex. "Visiter le site " avant la flèche)
  textTargets.forEach(({ node, fr, key }) => {
    node.data = lang === 'en' ? fr.replace(key, EN[key]) : fr;
  });

  attrTargets.forEach(({ el, attr, fr }) => {
    el.setAttribute(attr, lang === 'en' ? EN[fr.trim()] : fr);
  });

  document.getElementById('langCurrent').textContent = lang.toUpperCase();
  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });

  try { localStorage.setItem('lang', lang); } catch (e) { /* stockage indisponible : la langue ne sera pas retenue */ }
};

// Sélecteur de langue : bouton FR/EN avec flèche + petit menu déroulant
const langSwitch = document.getElementById('langSwitch');
const langBtn = document.getElementById('langBtn');

if (langSwitch && langBtn) {
  collectTargets();

  const setOpen = (open) => {
    langSwitch.classList.toggle('open', open);
    langBtn.setAttribute('aria-expanded', String(open));
  };

  langBtn.addEventListener('click', () => setOpen(!langSwitch.classList.contains('open')));

  langSwitch.querySelectorAll('[data-lang]').forEach(btn => {
    btn.addEventListener('click', () => {
      setOpen(false);
      if (btn.dataset.lang === currentLang) return;

      // Petit fondu pendant le changement de langue
      const sheet = document.querySelector('.sheet');
      sheet.classList.add('lang-fade');
      setTimeout(() => {
        applyLang(btn.dataset.lang);
        sheet.classList.remove('lang-fade');
      }, 180);
    });
  });

  document.addEventListener('click', (e) => { if (!langSwitch.contains(e.target)) setOpen(false); });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') setOpen(false); });

  let saved = 'fr';
  try { saved = localStorage.getItem('lang') || 'fr'; } catch (e) { /* stockage indisponible */ }
  applyLang(LANGS.includes(saved) ? saved : 'fr');
}
